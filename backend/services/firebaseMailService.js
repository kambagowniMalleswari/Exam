/**
 * Dispatches a Password Reset Email using Google Firebase Auth REST API.
 * The email contains an official, cryptographically secure password reset link
 * generated by Firebase and dispatched through Google's high-deliverability mail servers.
 *
 * @param {Object} params
 * @param {string} params.email - Target recipient email
 * @returns {Promise<Object>} Delivery result
 */
export const sendFirebasePasswordReset = async ({ email }) => {
  const apiKey = getApiKey();

  if (!email || !email.includes("@")) {
    throw new Error("A valid recipient email address is required.");
  }

  if (!apiKey) {
    throw new Error("FIREBASE_API_KEY is not configured in backend environment.");
  }

  const endpoint = `https://identitytoolkit.googleapis.com/v1/accounts:sendOobCode?key=${apiKey}`;

  const startTime = Date.now();
  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      requestType: "PASSWORD_RESET",
      email: email.trim().toLowerCase()
    })
  });

  const durationMs = Date.now() - startTime;
  const data = await response.json();

  if (!response.ok) {
    const errorMsg = data?.error?.message || `Firebase HTTP Error ${response.status}`;
    console.error(`[Firebase Mail Error] (${durationMs}ms):`, errorMsg);
    
    // Provide user-friendly interpretations
    if (errorMsg === "EMAIL_NOT_FOUND") {
      return {
        success: true, // For security, do not leak whether email is in Firebase Auth pool
        emailSent: true,
        email: email.trim().toLowerCase(),
        provider: "firebase",
        durationMs,
        message: `Password reset instructions have been dispatched for ${email}. Please check your inbox and spam folder.`,
        note: "Handled securely via Firebase Identity Toolkit."
      };
    }
    
    throw new Error(`Firebase Email Dispatch Failed: ${errorMsg}`);
  }

  console.log(`[Firebase Mail Sent] Password Reset to: ${email} (${durationMs}ms)`);
  return {
    success: true,
    emailSent: true,
    email: data.email || email,
    provider: "firebase",
    durationMs,
    message: `Firebase password reset link successfully sent to ${email}.`,
    details: data
  };
};

/**
 * Dispatches an Email Verification link for a Firebase User via ID Token
 * @param {Object} params
 * @param {string} params.idToken - Firebase User ID Token
 */
export const sendFirebaseEmailVerification = async ({ idToken }) => {
  const apiKey = getApiKey();

  if (!idToken) {
    throw new Error("Firebase User idToken is required for email verification.");
  }

  const endpoint = `https://identitytoolkit.googleapis.com/v1/accounts:sendOobCode?key=${apiKey}`;

  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      requestType: "VERIFY_EMAIL",
      idToken
    })
  });

  const data = await response.json();
  if (!response.ok) {
    throw new Error(data?.error?.message || "Failed to dispatch verification email via Firebase");
  }

  return {
    success: true,
    provider: "firebase",
    email: data.email,
    message: "Firebase verification email dispatched successfully."
  };
};

